export const getTranslation = (path, lang = 'EN') => {
  const keys = path.split('.');
  let current = TRANSLATIONS;
  for (const k of keys) {
    if (current && current[k]) {
      current = current[k];
    } else {
      return path;
    }
  }
  if (typeof current === 'object' && current[lang]) {
    return current[lang];
  }
  if (typeof current === 'object' && current['EN']) {
    return current['EN'];
  }
  return typeof current === 'string' ? current : path;
};
